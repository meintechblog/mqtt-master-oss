import { describe, it, expect } from 'vitest';
import { generateMosquittoBridgeConf } from '../server/services/bridge-config-generator.js';

const HEADER_RE = /^# Generated by mqtt-master/;

describe('generateMosquittoBridgeConf — header & empty input', () => {
  it('returns just the header block for an empty list', () => {
    const out = generateMosquittoBridgeConf([]);
    expect(out).toMatch(HEADER_RE);
    // No `connection ` line should appear when there are zero bridges
    expect(out).not.toMatch(/^connection /m);
    // Length should be small — a couple of header lines.
    expect(out.length).toBeLessThan(400);
  });
});

describe('generateMosquittoBridgeConf — canonical from-legacy case', () => {
  // Typical use case: mirror everything from a legacy broker.
  // The exact lines below are what mosquitto must see verbatim.
  const canonical = [
    {
      connectionName: 'from-legacy',
      remoteHost: '203.0.113.8',
      remotePort: 1883,
      topics: [{ pattern: '#', direction: 'in', qos: 0 }],
      enabled: true,
    },
  ];

  it('emits the exact canonical lines in order', () => {
    const out = generateMosquittoBridgeConf(canonical);
    const expected = [
      'connection from-legacy',
      'address 203.0.113.8:1883',
      'remote_clientid mqtt-master-bridge-from-legacy',
      'cleansession false',
      'notifications false',
      'try_private true',
      'bridge_protocol_version mqttv311',
      'topic # in 0 "" ""',
    ];
    for (const line of expected) {
      expect(out).toContain(line);
    }
    // Order check: each consecutive expected line must appear AFTER the previous one.
    let lastIdx = -1;
    for (const line of expected) {
      const idx = out.indexOf(line);
      expect(idx).toBeGreaterThan(lastIdx);
      lastIdx = idx;
    }
  });

  it('does NOT emit remote_username / remote_password for the canonical no-auth case', () => {
    const out = generateMosquittoBridgeConf(canonical);
    expect(out).not.toMatch(/^remote_username/m);
    expect(out).not.toMatch(/^remote_password/m);
  });
});

describe('generateMosquittoBridgeConf — each direction emits the right topic line', () => {
  function singleTopicBridge(direction) {
    return [
      {
        connectionName: `dir-${direction}`,
        remoteHost: '198.51.100.1',
        remotePort: 1883,
        topics: [{ pattern: 'sensors/#', direction, qos: 1 }],
        enabled: true,
      },
    ];
  }

  it('direction=in', () => {
    expect(generateMosquittoBridgeConf(singleTopicBridge('in')))
      .toContain('topic sensors/# in 1 "" ""');
  });
  it('direction=out', () => {
    expect(generateMosquittoBridgeConf(singleTopicBridge('out')))
      .toContain('topic sensors/# out 1 "" ""');
  });
  it('direction=both', () => {
    expect(generateMosquittoBridgeConf(singleTopicBridge('both')))
      .toContain('topic sensors/# both 1 "" ""');
  });
});

describe('generateMosquittoBridgeConf — auth handling', () => {
  it('emits remote_username AND remote_password when username is set', () => {
    const out = generateMosquittoBridgeConf([
      {
        connectionName: 'authed',
        remoteHost: '198.51.100.5',
        remotePort: 1883,
        remoteUsername: 'alice',
        remotePassword: 's3cret',
        topics: [{ pattern: '#', direction: 'in', qos: 0 }],
        enabled: true,
      },
    ]);
    expect(out).toMatch(/^remote_username alice$/m);
    expect(out).toMatch(/^remote_password s3cret$/m);
  });

  it('does NOT emit auth lines when username is empty string', () => {
    const out = generateMosquittoBridgeConf([
      {
        connectionName: 'noauth',
        remoteHost: '198.51.100.5',
        remotePort: 1883,
        remoteUsername: '',
        remotePassword: '',
        topics: [{ pattern: '#', direction: 'in', qos: 0 }],
        enabled: true,
      },
    ]);
    expect(out).not.toMatch(/^remote_username/m);
    expect(out).not.toMatch(/^remote_password/m);
  });

  it('does NOT emit auth lines when username is missing', () => {
    const out = generateMosquittoBridgeConf([
      {
        connectionName: 'noauth2',
        remoteHost: '198.51.100.5',
        remotePort: 1883,
        topics: [{ pattern: '#', direction: 'in', qos: 0 }],
        enabled: true,
      },
    ]);
    expect(out).not.toMatch(/^remote_username/m);
    expect(out).not.toMatch(/^remote_password/m);
  });
});

describe('generateMosquittoBridgeConf — multiple topics + bridges', () => {
  it('preserves topic order within a bridge', () => {
    const out = generateMosquittoBridgeConf([
      {
        connectionName: 'multi',
        remoteHost: '198.51.100.5',
        remotePort: 1883,
        topics: [
          { pattern: 'a/#', direction: 'in', qos: 0 },
          { pattern: 'b/#', direction: 'out', qos: 1 },
          { pattern: 'c/#', direction: 'both', qos: 2 },
        ],
        enabled: true,
      },
    ]);
    const ai = out.indexOf('topic a/# in 0 "" ""');
    const bi = out.indexOf('topic b/# out 1 "" ""');
    const ci = out.indexOf('topic c/# both 2 "" ""');
    expect(ai).toBeGreaterThan(-1);
    expect(bi).toBeGreaterThan(ai);
    expect(ci).toBeGreaterThan(bi);
  });

  it('separates multiple bridges with a blank line, in input order', () => {
    const out = generateMosquittoBridgeConf([
      {
        connectionName: 'alpha',
        remoteHost: '198.51.100.1',
        remotePort: 1883,
        topics: [{ pattern: '#', direction: 'in', qos: 0 }],
        enabled: true,
      },
      {
        connectionName: 'beta',
        remoteHost: '198.51.100.2',
        remotePort: 1883,
        topics: [{ pattern: '#', direction: 'in', qos: 0 }],
        enabled: true,
      },
    ]);
    const alpha = out.indexOf('connection alpha');
    const beta = out.indexOf('connection beta');
    expect(alpha).toBeGreaterThan(-1);
    expect(beta).toBeGreaterThan(alpha);
    // Between alpha block and beta block there should be a blank line.
    const between = out.slice(alpha, beta);
    expect(between).toMatch(/\n\n/);
  });
});

describe('generateMosquittoBridgeConf — disabled bridges', () => {
  it('comments out every line of a disabled bridge and prepends a marker', () => {
    const out = generateMosquittoBridgeConf([
      {
        connectionName: 'offline',
        remoteHost: '198.51.100.5',
        remotePort: 1883,
        topics: [{ pattern: '#', direction: 'in', qos: 0 }],
        enabled: false,
      },
    ]);
    expect(out).toMatch(/^# DISABLED: offline$/m);
    // Real `connection offline` should NOT appear — only the commented version.
    expect(out).not.toMatch(/^connection offline$/m);
    expect(out).toMatch(/^# connection offline$/m);
    expect(out).toMatch(/^# address 198\.51\.100\.5:1883$/m);
    expect(out).toMatch(/^# topic # in 0 "" ""$/m);
  });
});

describe('generateMosquittoBridgeConf — connection-name validation', () => {
  function bridgeWithName(name) {
    return [{
      connectionName: name,
      remoteHost: '198.51.100.5',
      remotePort: 1883,
      topics: [{ pattern: '#', direction: 'in', qos: 0 }],
      enabled: true,
    }];
  }
  it('rejects empty connection name', () => {
    expect(() => generateMosquittoBridgeConf(bridgeWithName('')))
      .toThrow(/Invalid connection name/);
  });
  it('rejects 65-char connection name', () => {
    const name = 'a'.repeat(65);
    expect(() => generateMosquittoBridgeConf(bridgeWithName(name)))
      .toThrow(/Invalid connection name/);
  });
  it('accepts 64-char connection name', () => {
    const name = 'a'.repeat(64);
    expect(() => generateMosquittoBridgeConf(bridgeWithName(name))).not.toThrow();
  });
  it('rejects connection name with a space', () => {
    expect(() => generateMosquittoBridgeConf(bridgeWithName('my bridge')))
      .toThrow(/Invalid connection name/);
  });
  it('rejects connection name with a slash', () => {
    expect(() => generateMosquittoBridgeConf(bridgeWithName('a/b')))
      .toThrow(/Invalid connection name/);
  });
});

describe('generateMosquittoBridgeConf — topic line validation', () => {
  function bridgeWithTopic(t) {
    return [{
      connectionName: 'ok',
      remoteHost: '198.51.100.5',
      remotePort: 1883,
      topics: [t],
      enabled: true,
    }];
  }
  it('rejects unknown direction', () => {
    expect(() => generateMosquittoBridgeConf(bridgeWithTopic({ pattern: '#', direction: 'sideways', qos: 0 })))
      .toThrow(/direction/);
  });
  it('rejects qos=3', () => {
    expect(() => generateMosquittoBridgeConf(bridgeWithTopic({ pattern: '#', direction: 'in', qos: 3 })))
      .toThrow(/qos/);
  });
  it('rejects newline in topic pattern (config-injection guard)', () => {
    expect(() => generateMosquittoBridgeConf(bridgeWithTopic({ pattern: '#\nconnection evil', direction: 'in', qos: 0 })))
      .toThrow(/newline|CR|LF|control/);
  });
  it('rejects newline in remote_password value (config-injection guard)', () => {
    expect(() => generateMosquittoBridgeConf([{
      connectionName: 'ok',
      remoteHost: '198.51.100.5',
      remotePort: 1883,
      remoteUsername: 'alice',
      remotePassword: 'pw\nconnection evil',
      topics: [{ pattern: '#', direction: 'in', qos: 0 }],
      enabled: true,
    }])).toThrow(/newline|CR|LF|control/);
  });
});
